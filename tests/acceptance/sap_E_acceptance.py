def _split_methods(path):
    """Return (skeleton lines, {method name: body}) for the implementation part of the class (after the DEFINITION's ENDCLASS.)."""
    text = path.read_bytes().decode("utf-8").replace(chr(13) + chr(10), chr(10))
    impl = text[text.index("ENDCLASS.") :]
    bodies = {m.group(1): m.group(2) for m in _METHOD_RE.finditer(impl)}
    skeleton = [line.rstrip() for line in _METHOD_RE.sub("", impl).split(chr(10))]
    return skeleton, bodies


def test_nothing_outside_changed_methods_changed():
    """Everything outside the method bodies (including the methods' own order) is as in the original, and the methods the upstream fix does not change are byte-identical. subtract, add, subtractsecs and any new method may change."""
    new_skel, new_bodies = _split_methods(TARGET)
    old_skel, old_bodies = _split_methods(ORIGINAL)
    blank = lambda lines: [line for line in lines if line.strip()]
    assert blank(new_skel) == blank(old_skel), "code outside the method bodies changed"
    for name in UNCHANGED_METHODS:
        assert new_bodies.get(name) == old_bodies.get(name), f"method {name} changed"


def _lint_keys(issues):
    """Issue text without the row number, so a moved issue is still the same issue."""
    return Counter(re.sub(r" \(.*:\d+\)$", "", s) for s in issues)


def test_no_new_abaplint_issues_in_the_edited_file():
    """abaplint with the project's own config plus the kernel-write rule, compared to the original: the edited file may not add an issue the original does not have (the kernel-write rule already fires on the original's WRITE '@KERNEL lines)."""
    try:
        _refuse_new_risky_text()
        new = t.run_abaplint(CFG, {REL_CLASS: TARGET}, timeout_s=600, trusted=(REL_CLASS,))
        old = t.run_abaplint(CFG, {REL_CLASS: ORIGINAL}, timeout_s=600, trusted=(REL_CLASS,))
    except (t.AbapTextRefused, t.RunnerError) as exc:
        raise AssertionError(f"abaplint could not be run: {type(exc).__name__}: {exc}") from None
    extra = _lint_keys(new) - _lint_keys(old)
    assert not extra, list(extra.elements())
