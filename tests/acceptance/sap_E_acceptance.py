def _refuse_new_risky_text():
    """The original class has risky-looking text (WRITE '@KERNEL, as the transpiler needs it), so the class is trusted and only the lines the writer ADDED (compared to the original, as a multiset) are checked. A writer-added CALL FUNCTION, @KERNEL, etc. is still refused."""
    orig = ORIGINAL.read_text(encoding="utf-8").replace(chr(13) + chr(10), chr(10)).split(chr(10))
    added = []
    for line in TARGET.read_text(encoding="utf-8").replace(chr(13) + chr(10), chr(10)).split(chr(10)):
        if line in orig:
            orig.remove(line)
        else:
            added.append(line)
    problems = t.check_abap_text(chr(10).join(added))
    if problems:
        raise t.AbapTextRefused("; ".join(problems))

